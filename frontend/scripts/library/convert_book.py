"""Convert a Defence Pathshala eBook PDF into Free Library reader pages.

Usage (from frontend/):
  pip install pymupdf pillow
  python3 scripts/library/convert_book.py <slug> <book.pdf> --reader 1-38 --quiz 39-45
  python3 scripts/library/convert_book.py --hotspots   # rebuild src/lib/library/hotspots.ts

- Renders only the reader pages to public/library/<slug>/page-NN.webp (1215 px wide, like the
  monthly capsule). The PDF itself, the MCQ pages and the answer-key pages are never published:
  the MCQs are served as the interactive quiz (src/lib/library/quiz-<slug>.ts).
- Saves the PDF's internal links (contents rows, "INDEX ↑" headers) to scripts/library/<slug>.links.json.
  Links into the quiz pages become target 0 (= jump to the interactive practice).
"""
import argparse, io, json, os, re, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
FRONTEND = HERE.parent.parent
WIDTH = 1215


def span(text):
    a, b = (int(x) for x in text.split("-"))
    return list(range(a, b + 1))


def convert(slug, pdf, reader, quiz):
    import pymupdf
    from PIL import Image
    doc = pymupdf.open(pdf)
    out = FRONTEND / "public" / "library" / slug
    out.mkdir(parents=True, exist_ok=True)
    for old in out.glob("*.webp"):
        old.unlink()
    links = []
    for i, page in enumerate(doc):
        n = i + 1
        if n not in reader:
            continue
        pw, ph = page.rect.width, page.rect.height
        for link in page.get_links():
            m = re.fullmatch(r"p(\d+)", link.get("name") or link.get("nameddest") or "")
            if not m:
                continue
            target = int(m.group(1))
            target = 0 if target in quiz else target
            if target and target not in reader:
                continue
            r = link["from"]
            links.append({"page": n, "target": target, "left": round(r.x0 / pw * 100, 2), "top": round(r.y0 / ph * 100, 2),
                          "width": round((r.x1 - r.x0) / pw * 100, 2), "height": round((r.y1 - r.y0) / ph * 100, 2)})
        pix = page.get_pixmap(matrix=pymupdf.Matrix(WIDTH / pw, WIDTH / pw), alpha=False)
        Image.open(io.BytesIO(pix.tobytes("png"))).save(out / f"page-{n:02d}.webp", "WEBP", quality=80, method=6)
    (HERE / f"{slug}.links.json").write_text(json.dumps(links, indent=0) + "\n")
    print(f"{slug}: {len(reader)} pages ({pix.width}x{pix.height}), {len(links)} links. Now run --hotspots.")


def write_hotspots():
    lines = ["// GENERATED by scripts/library/convert_book.py --hotspots from the source PDFs' internal links.",
             "// target 0 = the interactive MCQ practice, which replaces the MCQ and answer-key pages.",
             "// Small header links are padded so they are a usable tap target on phones.", "",
             "export type LibraryHotspot = { page: number; target: number; left: number; top: number; width: number; height: number };", "",
             "export const LIBRARY_HOTSPOTS: Record<string, LibraryHotspot[]> = {"]
    for f in sorted(HERE.glob("*.links.json")):
        lines.append(f'  "{f.name[:-len(".links.json")]}": [')
        for l in json.loads(f.read_text()):
            left, top, w, h = l["left"], l["top"], l["width"], l["height"]
            if h < 2.5:  # "INDEX ↑" header link
                left, top, w, h = 76.0, 0.3, 21.0, 3.6
            lines.append(f'    {{ page: {l["page"]}, target: {l["target"]}, left: {left}, top: {top}, width: {w}, height: {h} }},')
        lines.append("  ],")
    lines.append("};")
    (FRONTEND / "src" / "lib" / "library" / "hotspots.ts").write_text("\n".join(lines) + "\n")
    print("wrote src/lib/library/hotspots.ts")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("slug", nargs="?")
    ap.add_argument("pdf", nargs="?")
    ap.add_argument("--reader", help="reader page range, e.g. 1-38")
    ap.add_argument("--quiz", help="MCQ + answer-key page range, e.g. 39-45")
    ap.add_argument("--hotspots", action="store_true")
    a = ap.parse_args()
    if a.hotspots:
        write_hotspots()
    elif a.slug and a.pdf and a.reader and a.quiz:
        convert(a.slug, a.pdf, span(a.reader), span(a.quiz))
    else:
        ap.print_help(); sys.exit(1)
